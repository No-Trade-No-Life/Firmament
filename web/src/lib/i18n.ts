export function cadenceLabel(cadence: "daily" | "weekly" | "monthly", t: Copy) {
  if (cadence === "weekly") return t.cadenceWeekly
  if (cadence === "monthly") return t.cadenceMonthly
  return t.cadenceDaily
}

export function granularityLabel(granularity: "hour" | "day" | "month", t: Copy) {
  if (granularity === "hour") return t.granularityHour
  if (granularity === "month") return t.granularityMonth
  return t.granularityDay
}

export function columnTypeLabel(type: "integer" | "real" | "text" | "boolean" | "timestamp", t: Copy) {
  if (type === "integer") return t.typeInteger
  if (type === "real") return t.typeReal
  if (type === "boolean") return t.typeBoolean
  if (type === "timestamp") return t.typeTimestamp
  return t.typeText
}

export const copy = { zh, en }
export type Copy = typeof zh

/// The language the user picked explicitly, if any. Nothing else is persisted,
/// so "no stored value" means "follow the Linkit profile until the user decides".
export function storedLocale(): Locale | null {
  if (typeof window === "undefined") return null
  const stored = window.localStorage.getItem(localeStorageKey)
  return stored === "zh" || stored === "en" ? stored : null
}

export const initialLocale: Locale = storedLocale()
  ?? (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en")

export function persistLocale(locale: Locale) {
  window.localStorage.setItem(localeStorageKey, locale)
}

export function negotiateLocale(languages?: readonly string[]): Locale | undefined {
  const match = languages?.find((language) => {
    const normalized = language.toLowerCase()
    return normalized.startsWith("zh") || normalized.startsWith("en")
  })
  if (!match) return undefined
  return match.toLowerCase().startsWith("zh") ? "zh" : "en"
}
