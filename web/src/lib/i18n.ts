export type Copy = typeof zh

export const initialLocale: Locale = (() => {
  if (typeof window === "undefined") return "zh"
  const stored = window.localStorage.getItem(localeStorageKey)
  if (stored === "zh" || stored === "en") return stored
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en"
})()

export function persistLocale(locale: Locale) {
  window.localStorage.setItem(localeStorageKey, locale)
}

export function negotiateLocale(languages?: readonly string[]): Locale | undefined {
  const match = languages?.find((language) => {
    const normalized = language.toLowerCase()
    return normalized.startsWith("zh") || normalized.startsWith("en")
  })
  if (!match) return undefined
  return match.toLowerCase().startsWith("zh") ? "zh" : "en"
}
